#!/usr/bin/env bash
# Disclaimer: Usage of this tool must be under the guidance of Nutanix Support or an authorized partner
# Summary: One-time PCVM install for Flow SMSP field B/R (config, RSA key, systemd timer)
# Version of the script: 1.0
# Compatible software version(s): Prism Central with Flow SMSP (confirm target PC/Flow versions before use)
# Brief syntax usage: ./install.sh
# Caveats: Interactive. Creates RSA key and enables backup timer. Operator must install pubkey on
#   backup host and pin host key. Re-run validation process for any new package version.
set -euo pipefail

PKG_DIR="$(cd "$(dirname "$0")" && pwd)"
DEST="${FLOW_BR_HOME:-/home/nutanix/flow_br}"
CONF="$DEST/flow_br.conf"
SSH_KEY="${SSH_KEY:-/home/nutanix/.ssh/flow_br_backup}"
PYTHON_DEFAULT="/home/nutanix/.venvs/bin/bin/python3"
die() { echo "install: $*" >&2; exit 1; }
info() { echo "install: $*"; }

need_user() {
  [[ "$(id -un)" == "nutanix" ]] || die "run as nutanix on the PCVM"
}

prompt() {
  # prompt "label" "default" -> sets REPLY
  local label="$1" default="${2:-}"
  if [[ -n "$default" ]]; then
    read -r -p "$label [$default]: " REPLY
    REPLY="${REPLY:-$default}"
  else
    while true; do
      read -r -p "$label: " REPLY
      [[ -n "$REPLY" ]] && break
      echo "  (required)"
    done
  fi
}

write_conf() {
  umask 077
  # Quote every value — OnCalendar has spaces/slashes and must survive `source`.
  cat >"$CONF" <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
BACKUP_HOST=$(printf '%q' "$BACKUP_HOST")
BACKUP_USER=$(printf '%q' "$BACKUP_USER")
BACKUP_PATH=$(printf '%q' "$BACKUP_PATH")
SSH_KEY=$(printf '%q' "$SSH_KEY")
KNOWN_HOSTS=$(printf '%q' "$DEST/known_hosts")
PYTHON=$(printf '%q' "$PYTHON")
FLOW_BR_SCRIPT=$(printf '%q' "$DEST/flow_br_poc.py")
BACKUP_ONCALENDAR=$(printf '%q' "$BACKUP_ONCALENDAR")
BACKUP_INTERVAL_HOURS=$(printf '%q' "${BACKUP_INTERVAL_HOURS:-0}")
BACKUP_RANDOMIZED_DELAY_SEC=$(printf '%q' "$BACKUP_RANDOMIZED_DELAY_SEC")
BACKUP_RETAIN_COUNT=$(printf '%q' "$BACKUP_RETAIN_COUNT")
BACKUP_NODE_IP=$(printf '%q' "$BACKUP_NODE_IP")
EOF
  chmod 600 "$CONF"
  info "wrote $CONF"
}

install_files() {
  mkdir -p "$DEST/logs" "$DEST/systemd"
  chmod 700 "$DEST"
  cp -f "$PKG_DIR/flow_br_poc.py" "$DEST/flow_br_poc.py"
  cp -f "$PKG_DIR/flow-br" "$DEST/flow-br"
  chmod 755 "$DEST/flow-br"
  cp -f "$PKG_DIR/flow_br.conf.example" "$DEST/flow_br.conf.example"
  cp -f "$PKG_DIR/systemd/flow-br-backup.service" "$DEST/systemd/"
  cp -f "$PKG_DIR/systemd/flow-br-backup.timer" "$DEST/systemd/"
  ln -sfn "$DEST/flow-br" "$HOME/bin/flow-br" 2>/dev/null || true
  mkdir -p "$HOME/bin"
  ln -sfn "$DEST/flow-br" "$HOME/bin/flow-br"
  info "installed scripts under $DEST"
}

ensure_ssh_key() {
  mkdir -p "$(dirname "$SSH_KEY")"
  chmod 700 "$(dirname "$SSH_KEY")"
  if [[ ! -f "$SSH_KEY" ]]; then
    info "generating RSA-4096 key (FIPS-safe): $SSH_KEY"
    ssh-keygen -t rsa -b 4096 -f "$SSH_KEY" -N '' -C "flow_br_backup@$(hostname -s)"
  else
    info "reusing existing key $SSH_KEY"
  fi
  chmod 600 "$SSH_KEY"
  [[ -f "${SSH_KEY}.pub" ]] || die "missing ${SSH_KEY}.pub"
}

ensure_known_hosts() {
  local kh="$DEST/known_hosts"
  if [[ -f "$kh" ]]; then
    info "known_hosts already present: $kh"
    return 0
  fi
  cat <<EOF

Pin the backup host SSH host key (required; PCVM FIPS cannot use ssh-keyscan).

On the BACKUP HOST run:
  awk -v h=$BACKUP_HOST '{print h, \$1, \$2}' /etc/ssh/ssh_host_ecdsa_key.pub

Paste the single line below, then Ctrl-D:

EOF
  mkdir -p "$DEST"
  umask 077
  : >"$kh"
  cat >>"$kh"
  chmod 600 "$kh"
  [[ -s "$kh" ]] || die "known_hosts is empty"
  info "wrote $kh"
}

print_pubkey_instructions() {
  cat <<EOF

=== ACTION REQUIRED on backup host ===
Append this public key to ~${BACKUP_USER}/.ssh/authorized_keys on ${BACKUP_HOST}:

$(cat "${SSH_KEY}.pub")

Also ensure remote directory exists (backup will mkdir -p):
  ${BACKUP_PATH}

EOF
}

render_timer() {
  # Substitute OnCalendar / RandomizedDelay from conf into installed timer.
  local src="$PKG_DIR/systemd/flow-br-backup.timer"
  local out="$DEST/systemd/flow-br-backup.timer"
  sed -e "s|@BACKUP_ONCALENDAR@|$BACKUP_ONCALENDAR|g" \
      -e "s|@BACKUP_RANDOMIZED_DELAY_SEC@|$BACKUP_RANDOMIZED_DELAY_SEC|g" \
      "$src" >"$out"
  cp -f "$PKG_DIR/systemd/flow-br-backup.service" "$DEST/systemd/flow-br-backup.service"
}

install_systemd() {
  render_timer
  # System units only: user units depend on linger state that PC upgrade can drop.
  sudo -n true 2>/dev/null || die "passwordless sudo required to install systemd units"
  # PC ZK survives upgrades: atlas reads it to re-arm the timer and to alert.
  local interval_secs=86400
  (( BACKUP_INTERVAL_HOURS > 0 )) && interval_secs=$(( BACKUP_INTERVAL_HOURS * 3600 ))
  "$PYTHON" "$DEST/flow_br_poc.py" zk-init --backup-node-ip "$BACKUP_NODE_IP" \
      --interval-secs "$interval_secs" --install-path "$DEST" \
    || die "could not record backup config in PC ZK"
  FLOW_BR_HOME="$DEST" "$DEST/flow-br" ensure-timer
}

this_pcvm_ip() {
  local svmips_bin=/usr/local/nutanix/cluster/bin/svmips ip
  command -v svmips &>/dev/null && svmips_bin=$(command -v svmips)
  [[ -x "$svmips_bin" ]] || return 1
  for ip in $("$svmips_bin" 2>/dev/null); do
    hostname -I | tr ' ' '\n' | grep -qxF "$ip" && { echo "$ip"; return 0; }
  done
  return 1
}

main() {
  need_user
  [[ -f "$PKG_DIR/flow_br_poc.py" ]] || die "flow_br_poc.py missing next to install.sh"
  [[ -f "$PKG_DIR/flow-br" ]] || die "flow-br missing next to install.sh"

  echo "Flow SMSP backup/restore — field install"
  echo "Package: $PKG_DIR"
  echo

  prompt "Backup host (IP or DNS)"
  BACKUP_HOST="$REPLY"
  prompt "Backup SSH user" "nutanix"
  BACKUP_USER="$REPLY"
  prompt "Remote backup directory" "~/flow_backups"
  BACKUP_PATH="$REPLY"

  echo
  echo "Backup schedule:"
  echo "  1) every N hours   (e.g. 1, 2, 4, 6, 12)"
  echo "  2) once daily at HH:MM UTC"
  prompt "Schedule type" "1"
  local sched_type="$REPLY"
  local retain_default="14"
  local delay_default="300"
  if [[ "$sched_type" == "2" ]]; then
    prompt "Daily backup time UTC (HH:MM)" "02:30"
    local hhmm="$REPLY"
    [[ "$hhmm" =~ ^([01][0-9]|2[0-3]):[0-5][0-9]$ ]] \
      || die "time must be HH:MM 00:00-23:59 (got $hhmm)"
    BACKUP_ONCALENDAR="*-*-* ${hhmm}:00"
    BACKUP_INTERVAL_HOURS=0
    retain_default="14"
    delay_default="900"
  else
    prompt "Backup every N hours" "6"
    local n="$REPLY"
    [[ "$n" =~ ^[0-9]+$ ]] && (( n >= 1 && n <= 24 )) \
      || die "hours must be an integer 1-24 (got $n)"
    BACKUP_INTERVAL_HOURS="$n"
    if (( n == 1 )); then
      BACKUP_ONCALENDAR="hourly"
    else
      # systemd: every N hours on the hour, from 00:00 UTC
      BACKUP_ONCALENDAR="*-*-* 0/${n}:00:00"
    fi
    # Keep ~7 days of archives by default when running hourly-ish.
    retain_default=$(( 7 * 24 / n ))
    (( retain_default < 14 )) && retain_default=14
    delay_default=300
  fi
  info "OnCalendar=$BACKUP_ONCALENDAR"

  prompt "Random delay seconds (spread load)" "$delay_default"
  BACKUP_RANDOMIZED_DELAY_SEC="$REPLY"
  prompt "Retain newest N archives on backup host (0=keep all)" "$retain_default"
  BACKUP_RETAIN_COUNT="$REPLY"
  prompt "Python (Atlas venv)" "$PYTHON_DEFAULT"
  PYTHON="$REPLY"
  [[ -x "$PYTHON" ]] || die "not executable: $PYTHON"
  BACKUP_NODE_IP="$(this_pcvm_ip)" || die "cannot find this PCVM's IP in svmips"
  info "scheduled backups run on this PCVM ($BACKUP_NODE_IP)"

  install_files
  write_conf
  ensure_ssh_key
  print_pubkey_instructions
  read -r -p "Press Enter after the public key is installed on the backup host..."
  ensure_known_hosts

  cat <<EOF

Test SSH (BatchMode):
  ssh -F /dev/null -i $SSH_KEY -o IdentitiesOnly=yes -o BatchMode=yes \\
    -o StrictHostKeyChecking=yes -o UserKnownHostsFile=$DEST/known_hosts \\
    ${BACKUP_USER}@${BACKUP_HOST} 'echo ok'

EOF
  read -r -p "Run test backup now? [Y/n] " yn
  yn="${yn:-Y}"
  if [[ "$yn" == "Y" || "$yn" == "y" ]]; then
    "$DEST/flow-br" backup --now
  fi

  read -r -p "Enable systemd backup timer? [Y/n] " yn
  yn="${yn:-Y}"
  if [[ "$yn" == "Y" || "$yn" == "y" ]]; then
    install_systemd
  else
    render_timer
    info "units left in $DEST/systemd — enable later"
  fi

  cat <<EOF

Install complete.

  Config:   $CONF
  CLI:      $DEST/flow-br   (also ~/bin/flow-br)
  Status:   flow-br status
  Backup:   flow-br backup --now
  Cleanup:  flow-br cleanup [--apply]
  Restore:  flow-br restore [--dry-run]
  DR steps: flow-br recover-help

After a PC upgrade atlas re-installs the timer from $DEST/systemd
(state in PC ZK /appliance/logical/flow_smsp/field_br). To check:
  flow-br status
Stop backups:  flow-br disable

EOF
}

main "$@"
